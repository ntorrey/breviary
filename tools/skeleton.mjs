#!/usr/bin/env node
// Generates fill-in-the-blank source files in content-src/_skeleton/ listing every
// entry and field the app expects. Copy a file out of _skeleton (the build skips
// folders starting with "_"), fill in the text, and run `npm run build:content`.
// Empty fields are ignored by the build, so partially filled files are fine.
//
// Usage: npm run skeleton

import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildYear, calendarConfig } from '../js/calendar/index.js';
import { GENERAL_ROMAN_CALENDAR, MOVABLE_CELEBRATIONS, USA_CALENDAR } from '../js/calendar/sanctoral-data.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'content-src', '_skeleton');
const DOWS = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];

const PSALMODY = ['ant1', 'ps1', 'ant2', 'ps2', 'ant3', 'ps3'];
const F = {
  inv: ['invitatory_ant'],
  or: ['hymn', ...PSALMODY, 'verse', 'reading1', 'resp1', 'reading2', 'resp2', 'prayer'],
  mp: ['hymn', ...PSALMODY, 'reading', 'responsory', 'benedictus_ant', 'intercessions', 'prayer'],
  ep: ['hymn', ...PSALMODY, 'reading', 'responsory', 'magnificat_ant', 'intercessions', 'prayer'],
  daytimePsalmody: PSALMODY,
  daytimeHour: ['hymn', 'reading', 'verse', 'prayer'],
  daytimeFull: ['hymn', ...PSALMODY, 'reading', 'verse', 'prayer'],
  np: ['hymn', 'ant1', 'ps1', 'ant2', 'ps2', 'reading', 'responsory', 'nunc_ant', 'prayer'],
  memorial: { or: ['reading2', 'resp2', 'prayer'], mp: ['benedictus_ant', 'prayer'], ep: ['magnificat_ant', 'prayer'] },
};

const out = [];
const entry = (key, fields, note) => {
  out.push(`=== ${key}`);
  if (note) out.push(`%% ${note}`);
  for (const f of fields) out.push(`--- ${f}`, '');
};
const flush = async (name, header) => {
  await writeFile(join(OUT, name), `%% ${header}\n%% Generated by tools/skeleton.mjs. Fill in the text under each field.\n\n${out.join('\n')}\n`);
  out.length = 0;
};

await mkdir(OUT, { recursive: true });

// Four-week psalter
for (let w = 1; w <= 4; w++) {
  for (const d of DOWS) {
    entry(`psalter/w${w}/${d}/inv`, F.inv);
    entry(`psalter/w${w}/${d}/or`, F.or);
    entry(`psalter/w${w}/${d}/mp`, F.mp);
    entry(`psalter/w${w}/${d}/daytime`, F.daytimePsalmody, 'Psalmody shared by Midmorning, Midday and Midafternoon Prayer');
    for (const h of ['terce', 'sext', 'none']) entry(`psalter/w${w}/${d}/${h}`, F.daytimeHour);
    if (d === 'sun') {
      entry(`psalter/w${w}/sun/ep1`, F.ep, 'Evening Prayer I (said on Saturday evening)');
      entry(`psalter/w${w}/sun/ep2`, F.ep, 'Evening Prayer II');
    } else if (d !== 'sat') {
      entry(`psalter/w${w}/${d}/ep`, F.ep);
    }
  }
  await flush(`psalter-week${w}.txt`, `Four-Week Psalter, Week ${w}`);
}
for (const h of ['terce', 'sext', 'none']) entry(`psalter/complementary/${h}`, PSALMODY);
await flush('psalter-complementary.txt', 'Complementary Psalmody (Daytime Prayer on solemnities)');

for (const d of DOWS) entry(`night/${d}`, F.np, d === 'sat' ? 'After Evening Prayer I of Sundays and solemnities' : d === 'sun' ? 'After Evening Prayer II of Sundays and solemnities' : '');
entry('night/common', ['hymn'], 'Hymns that may be used on any night');
await flush('night-prayer.txt', 'Night Prayer');

// Proper of Time: every temporal key that occurs over a span of years, under both calendars.
const temporal = new Map();
for (const region of ['usa', 'general']) {
  for (let y = 2026; y <= 2060; y++) {
    for (const day of buildYear(y, calendarConfig({ region })).values()) {
      const t = day.temporal;
      if (!temporal.has(t.key)) temporal.set(t.key, t);
    }
  }
}
const order = ['advent', 'christmas', 'lent', 'holyweek', 'triduum', 'easter', 'ordinary'];
const bySeason = {};
for (const [key, t] of temporal) (bySeason[key.split('/')[1]] ||= []).push([key, t]);
for (const season of order) {
  const list = (bySeason[season] || []).sort(([a], [b]) => a.localeCompare(b, 'en', { numeric: true }));
  for (const [key, t] of list) {
    const big = t.isSunday || t.prec <= 5;
    out.push(`%% ---- ${t.title}`);
    if (big) {
      entry(`${key}/inv`, F.inv);
      if (t.hasFirstVespers !== false && key !== 'time/easter/w1/sun') entry(`${key}/ep1`, F.ep);
      entry(`${key}/or`, F.or);
      entry(`${key}/mp`, F.mp);
      for (const h of ['terce', 'sext', 'none']) entry(`${key}/${h}`, F.daytimeFull);
      entry(`${key}/ep2`, F.ep);
    } else if (season === 'ordinary') {
      // Ordinary Time weekdays come almost entirely from the psalter; only the readings vary.
      entry(`${key}/or`, ['verse', 'reading1', 'resp1', 'reading2', 'resp2']);
    } else {
      entry(`${key}/inv`, F.inv);
      entry(`${key}/or`, F.or);
      entry(`${key}/mp`, F.mp);
      for (const h of ['terce', 'sext', 'none']) entry(`${key}/${h}`, F.daytimeFull);
      entry(`${key}/ep`, F.ep);
    }
  }
  await flush(`time-${season}.txt`, `Proper of Time: ${season}`);
}

// Proper of Saints
const rows = [...GENERAL_ROMAN_CALENDAR, ...USA_CALENDAR.add,
  ...MOVABLE_CELEBRATIONS.map((m) => ['movable', m.id, m.title, m.rank])];
for (const [date, id, title, rank] of rows.sort((a, b) => a[0].localeCompare(b[0]))) {
  out.push(`%% ---- ${date} ${title} (${rank})`);
  if (rank === 'S' || rank === 'F') {
    entry(`saints/${id}/inv`, F.inv);
    if (rank === 'S') entry(`saints/${id}/ep1`, F.ep);
    entry(`saints/${id}/or`, F.or);
    entry(`saints/${id}/mp`, F.mp);
    for (const h of ['terce', 'sext', 'none']) entry(`saints/${id}/${h}`, F.daytimeHour);
    entry(`saints/${id}/${rank === 'S' ? 'ep2' : 'ep'}`, F.ep);
  } else {
    for (const [h, fields] of Object.entries(F.memorial)) entry(`saints/${id}/${h}`, fields);
  }
}
await flush('saints.txt', 'Proper of Saints (General Roman Calendar + USA). Memorials list only the usual proper parts; add any other field the book gives as proper.');

// Commons
const COMMONS = ['dedication', 'bvm', 'bvm-saturday', 'apostles', 'martyrs', 'martyr', 'pastors', 'doctors', 'virgins', 'holy-men', 'holy-women', 'religious', 'mercy', 'educators'];
for (const c of COMMONS) {
  out.push(`%% ---- Common: ${c}`);
  entry(`commons/${c}/inv`, F.inv);
  entry(`commons/${c}/ep1`, F.ep);
  entry(`commons/${c}/or`, F.or);
  entry(`commons/${c}/mp`, F.mp);
  for (const h of ['terce', 'sext', 'none']) entry(`commons/${c}/${h}`, F.daytimeFull);
  entry(`commons/${c}/ep2`, F.ep);
  entry(`commons/${c}/ep`, F.ep, 'Evening Prayer for memorials');
}
await flush('commons.txt', 'Commons');

// Psalms and canticles
for (let n = 1; n <= 150; n++) entry(`psalms/${n}`, ['title', 'subtitle', 'text'], 'Long psalms divided in the psalter get separate entries, e.g. psalms/18-i, psalms/18-ii');
await flush('psalms.txt', 'Psalms (referenced from ps1/ps2/ps3 fields as psalms/<n>)');
for (const c of ['benedictus', 'magnificat', 'nunc-dimittis', 'invitatory-95', 'invitatory-100', 'invitatory-67', 'invitatory-24']) {
  entry(`canticles/${c}`, ['title', 'subtitle', 'text']);
}
out.push('%% Add Old and New Testament canticles here as they appear in the psalter, e.g. canticles/dan3-57-88');
await flush('canticles.txt', 'Gospel canticles, invitatory psalms, and other canticles');

entry('ordinary', ['intro_inv', 'intro', 'intro@lent', 'gloria', 'our_father', 'dismissal', 'conclusion', 'examen', 'blessing', 'te_deum',
  'marian@advent', 'marian@lent', 'marian@easter', 'marian@ordinary']);
await flush('ordinary.txt', 'The Ordinary (fixed texts)');

console.log(`Skeleton written to ${OUT}`);
