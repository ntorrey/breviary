#!/usr/bin/env node
// Downloads the reading fonts (all SIL Open Font License) from Google Fonts into
// fonts/ and writes css/fonts.css, so the app can use them offline.
// Only the Latin and Latin-extended subsets are kept (they cover the accents in saints' names).
// Usage: node tools/fetch-fonts.mjs

import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const FAMILIES = {
  literata: 'Literata:ital,wght@0,400..700;1,400..700',
  garamond: 'EB+Garamond:ital,wght@0,400..700;1,400..700',
  sourceserif: 'Source+Serif+4:ital,wght@0,400..700;1,400..700',
  atkinson: 'Atkinson+Hyperlegible:ital,wght@0,400;0,700;1,400;1,700',
};
// A current browser user agent makes Google serve woff2.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';

await mkdir(join(ROOT, 'fonts'), { recursive: true });
let css = '/* Generated by tools/fetch-fonts.mjs. Fonts: SIL Open Font License 1.1. */\n';
for (const [id, spec] of Object.entries(FAMILIES)) {
  const src = await (await fetch(`https://fonts.googleapis.com/css2?family=${spec}&display=swap`, { headers: { 'User-Agent': UA } })).text();
  // Each block is preceded by a /* subset */ comment.
  const blocks = [...src.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g)]
    .filter(([, subset]) => subset === 'latin' || subset === 'latin-ext');
  let n = 0;
  for (const [, subset, block] of blocks) {
    const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
    const style = block.match(/font-style:\s*(\w+)/)[1];
    const weight = block.match(/font-weight:\s*([\d ]+)/)[1].trim().replace(' ', '-');
    const file = `${id}-${style}-${weight}-${subset}.woff2`;
    await writeFile(join(ROOT, 'fonts', file), Buffer.from(await (await fetch(url)).arrayBuffer()));
    css += block.replace(url, `../fonts/${file}`).replace(/font-family:\s*'[^']+'/, `font-family: 'R-${id}'`) + '\n';
    n++;
  }
  console.log(`${id}: ${n} files`);
}
await writeFile(join(ROOT, 'css', 'fonts.css'), css);
console.log('Wrote css/fonts.css');
